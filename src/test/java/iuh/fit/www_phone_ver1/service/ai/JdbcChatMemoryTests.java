package iuh.fit.www_phone_ver1.service.ai;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.util.List;
import java.util.stream.IntStream;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.ai.chat.messages.AssistantMessage;
import org.springframework.ai.chat.messages.Message;
import org.springframework.ai.chat.messages.UserMessage;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabase;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabaseBuilder;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabaseType;

class JdbcChatMemoryTests {
  private EmbeddedDatabase database;
  private JdbcChatMemory memory;

  @BeforeEach
  void setUp() {
    database = new EmbeddedDatabaseBuilder().setType(EmbeddedDatabaseType.H2).build();
    JdbcTemplate jdbcTemplate = new JdbcTemplate(database);
    jdbcTemplate.execute(
        "CREATE TABLE chat_memory_messages ("
            + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
            + "conversation_id VARCHAR(128) NOT NULL, "
            + "message_type VARCHAR(16) NOT NULL, "
            + "message_text CLOB NOT NULL, "
            + "created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP)");
    memory = new JdbcChatMemory(jdbcTemplate);
  }

  @AfterEach
  void tearDown() {
    database.shutdown();
  }

  @Test
  void storesHistoryInDatabaseAndReturnsLastMessagesInConversationOrder() {
    memory.add(
        "conversation-1",
        List.of(
            new UserMessage("first question"),
            new AssistantMessage("first answer"),
            new UserMessage("second question")));

    JdbcChatMemory newMemoryInstance = new JdbcChatMemory(new JdbcTemplate(database));
    List<Message> restored = newMemoryInstance.get("conversation-1", 2);

    assertEquals(2, restored.size());
    assertEquals("first answer", restored.get(0).getText());
    assertEquals("second question", restored.get(1).getText());
  }

  @Test
  void clearsOnlyTheRequestedConversation() {
    memory.add("conversation-1", List.<Message>of(new UserMessage("one")));
    memory.add("conversation-2", List.<Message>of(new UserMessage("two")));

    memory.clear("conversation-1");

    assertTrue(memory.get("conversation-1", 20).isEmpty());
    assertEquals("two", memory.get("conversation-2", 20).get(0).getText());
  }

  @Test
  void retainsOnlyTheMostRecentTwentyMessagesPerConversation() {
    List<Message> messages =
        IntStream.range(0, 22)
            .<Message>mapToObj(index -> new UserMessage("message-" + index))
            .toList();
    memory.add("conversation-1", messages);

    List<Message> recent = memory.get("conversation-1", 20);

    assertEquals(20, recent.size());
    assertEquals("message-2", recent.get(0).getText());
    assertEquals("message-21", recent.get(19).getText());
  }
}
